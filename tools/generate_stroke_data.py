#!/usr/bin/env python3
"""Generate the bundled hanzi stroke-data shards for shenzhen-hanzi-animator.

Downloads the license-clean upstream ``hanzi-writer-data`` combined dataset at a
pinned commit, validates it, shards it by ``codePointAt(0) % 256``, minifies and
gzips each shard, and writes the shards plus a character index into the
library's Compose resources. Also emits ``tools/DATA_PROVENANCE.md``.

Usage:
    python3 tools/generate_stroke_data.py [--all-json PATH]

The output shards are committed to the repository; re-run this only to update the
pinned dataset.
"""
from __future__ import annotations

import argparse
import gzip
import json
import os
import sys
import urllib.request

# Pinned upstream commit for reproducible, license-clean provenance.
PINNED_SHA = "68d10a4b21150cae5e1ebbd223eed289cf32d90c"
UPSTREAM_REPO = "chanind/hanzi-writer-data"
ALL_JSON_URL = f"https://raw.githubusercontent.com/{UPSTREAM_REPO}/{PINNED_SHA}/data/all.json"

EXPECTED_CHAR_COUNT = 9574
SHARD_COUNT = 256

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT_DIR = os.path.join(
    REPO_ROOT, "library", "src", "commonMain", "composeResources", "files", "strokes"
)
PROVENANCE_PATH = os.path.join(REPO_ROOT, "tools", "DATA_PROVENANCE.md")


def load_all_json(local_path: str | None) -> dict:
    if local_path and os.path.exists(local_path):
        print(f"Reading dataset from {local_path}")
        with open(local_path, "r", encoding="utf-8") as f:
            return json.load(f)
    print(f"Downloading dataset from {ALL_JSON_URL}")
    with urllib.request.urlopen(ALL_JSON_URL) as response:
        return json.loads(response.read().decode("utf-8"))


def validate(data: dict) -> None:
    if len(data) != EXPECTED_CHAR_COUNT:
        raise SystemExit(
            f"Expected {EXPECTED_CHAR_COUNT} characters, got {len(data)}. Aborting."
        )
    mismatches = 0
    missing_medians = 0
    for char, entry in data.items():
        strokes = entry.get("strokes")
        medians = entry.get("medians")
        if not strokes:
            raise SystemExit(f"Character {char!r} has no strokes. Aborting.")
        if medians is None:
            missing_medians += 1
        elif len(strokes) != len(medians):
            mismatches += 1
    print(
        f"Validated {len(data)} characters "
        f"({mismatches} stroke/median count mismatches, "
        f"{missing_medians} without medians)."
    )


def shard_of(char: str) -> int:
    # Match Kotlin's codePointAt(0): shard on the first Unicode code point.
    return ord(char[0]) % SHARD_COUNT


def build_entry(entry: dict) -> dict:
    out = {"strokes": entry["strokes"], "medians": entry.get("medians", [])}
    if "radStrokes" in entry:
        out["radStrokes"] = entry["radStrokes"]
    return out


def write_gz(path: str, raw: bytes) -> int:
    with gzip.GzipFile(filename="", mode="wb", fileobj=open(path, "wb"), mtime=0, compresslevel=9) as gz:
        gz.write(raw)
    return os.path.getsize(path)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--all-json", help="Path to a local all.json (skips download).")
    args = parser.parse_args()

    data = load_all_json(args.all_json)
    validate(data)

    os.makedirs(OUTPUT_DIR, exist_ok=True)
    for existing in os.listdir(OUTPUT_DIR):
        if existing.endswith(".gz"):
            os.remove(os.path.join(OUTPUT_DIR, existing))

    shards: dict[int, dict] = {i: {} for i in range(SHARD_COUNT)}
    for char, entry in data.items():
        shards[shard_of(char)][char] = build_entry(entry)

    total_bytes = 0
    non_empty = 0
    for shard_id in range(SHARD_COUNT):
        bucket = shards[shard_id]
        raw = json.dumps(bucket, separators=(",", ":"), ensure_ascii=False).encode("utf-8")
        path = os.path.join(OUTPUT_DIR, f"{shard_id}.json.gz")
        total_bytes += write_gz(path, raw)
        if bucket:
            non_empty += 1

    # Character index: all characters concatenated (each read back by code point).
    index_raw = "".join(data.keys()).encode("utf-8")
    index_path = os.path.join(OUTPUT_DIR, "index.txt.gz")
    index_bytes = write_gz(index_path, index_raw)

    print(
        f"Wrote {SHARD_COUNT} shards ({non_empty} non-empty), "
        f"{total_bytes / 1_000_000:.2f} MB total; "
        f"index {index_bytes / 1000:.1f} KB."
    )

    write_provenance(len(data), total_bytes, index_bytes)
    print(f"Wrote provenance to {PROVENANCE_PATH}")


def write_provenance(char_count: int, total_bytes: int, index_bytes: int) -> None:
    content = f"""# Bundled stroke-data provenance

The stroke-data shards in
`library/src/commonMain/composeResources/files/strokes/` are generated by
`tools/generate_stroke_data.py` from the upstream **hanzi-writer-data** dataset.

| Field | Value |
|-------|-------|
| Source repository | https://github.com/{UPSTREAM_REPO} |
| Pinned commit | `{PINNED_SHA}` |
| Source file | `data/all.json` |
| Character count | {char_count} |
| Shards | {SHARD_COUNT} (`<codePoint % 256>.json.gz`) |
| Compressed size | {total_bytes / 1_000_000:.2f} MB |
| Index size | {index_bytes / 1000:.1f} KB (`index.txt.gz`) |

## Licensing

`hanzi-writer-data` is distributed under the MIT License. The underlying glyph
data derives from **Make Me a Hanzi**, itself derived from the Arphic PL fonts
(Arphic Public License). See the repository `NOTICE` file for the full
attribution chain.

## Regenerating

```
python3 tools/generate_stroke_data.py
```

Each shard is a minified JSON object mapping a character to its
`{{strokes, medians[, radStrokes]}}` entry, gzip-compressed at level 9 with a
zeroed mtime for reproducible output. The index concatenates every bundled
character (read back one Unicode code point at a time).
"""
    with open(PROVENANCE_PATH, "w", encoding="utf-8") as f:
        f.write(content)


if __name__ == "__main__":
    main()
